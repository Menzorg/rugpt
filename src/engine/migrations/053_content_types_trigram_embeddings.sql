-- Migration 053: content-type search + category/comment embeddings for RAG.
--
-- This is a forward-only schema/search migration. It intentionally does not
-- backfill embeddings: content_types.embedding is filled by ContentTypeService
-- on category create/update; user_files.comment_embedding is filled only for
-- manual comments by RAG ingest.
--
-- Search behavior:
--   * list_categories/search_content_types remains trigram search over active
--     content_types.name.
--   * concrete document search is TSV-first over user_files.tsv. The TSV column
--     includes filename, comment, and summary.
--   * abstract document search ranks by vec_dist - comment_dist * 0.15, where
--     comment_dist is sourced from a MATERIALIZED CTE of per-category cosine
--     distances (computed once per call). Files without a category use their own
--     comment_embedding distance; files with neither get comment_dist = 0.

CREATE EXTENSION IF NOT EXISTS pg_trgm;

CREATE INDEX IF NOT EXISTS idx_content_types_name_trgm
    ON content_types USING GIN (name gin_trgm_ops)
    WHERE is_active = true;

-- search_content_types(p_org_id, p_query, p_threshold)
-- Returns active content types for the org whose name is similar to p_query.
-- p_threshold: similarity threshold in [0,1]; lower = looser match (default 0.1).
CREATE OR REPLACE FUNCTION search_content_types(
    p_org_id    uuid,
    p_query     text,
    p_threshold real DEFAULT 0.1
)
RETURNS TABLE (
    id          uuid,
    org_id      uuid,
    name        text,
    description text,
    is_active   boolean,
    created_at  timestamptz,
    updated_at  timestamptz,
    similarity  real
)
LANGUAGE plpgsql STABLE AS $$
BEGIN
    RETURN QUERY
    SELECT
        ct.id,
        ct.org_id,
        ct.name,
        ct.description,
        ct.is_active,
        ct.created_at,
        ct.updated_at,
        similarity(ct.name, p_query) AS similarity
    FROM content_types ct
    WHERE ct.org_id = p_org_id
      AND ct.is_active = true
      AND similarity(ct.name, p_query) >= p_threshold
    ORDER BY similarity(ct.name, p_query) DESC, ct.name;
END;
$$;

COMMENT ON FUNCTION search_content_types(uuid, text, real) IS
    'Fuzzy trigram search over active content_types names for an org. '
    'p_threshold controls match looseness: lower = more results (default 0.1).';

