    'Generated by ContentTypeService; not mirrored into user_files.';

CREATE INDEX IF NOT EXISTS idx_content_types_embedding_hnsw
    ON content_types USING hnsw (embedding vector_cosine_ops)
    WHERE embedding IS NOT NULL AND is_active = true;

ALTER TABLE user_files
    ADD COLUMN IF NOT EXISTS comment_embedding vector(1024);

COMMENT ON COLUMN user_files.comment_embedding IS
    'Manual file-comment embedding for RAG search. '
    'Category-backed files use content_types.embedding via join instead.';

CREATE INDEX IF NOT EXISTS idx_user_files_comment_embedding_hnsw
    ON user_files USING hnsw (comment_embedding vector_cosine_ops)
    WHERE comment_embedding IS NOT NULL AND is_active = true;

-- Recreate generated TSV to ensure comments participate in concrete document search.
-- Weights are ordered D,C,B,A in ts_rank:
--   original_filename -> A = strongest lexical signal
--   comment           -> B = user/category-provided business context
--   summary           -> C = broader generated context
DROP INDEX IF EXISTS user_files_tsv_gin_idx;

ALTER TABLE user_files
    DROP COLUMN IF EXISTS tsv;

ALTER TABLE user_files
    ADD COLUMN tsv tsvector
        GENERATED ALWAYS AS (
            setweight(to_tsvector('russian', coalesce(original_filename, '')), 'A') ||
            setweight(to_tsvector('russian', coalesce(comment,           '')), 'B') ||
            setweight(to_tsvector('russian', coalesce(summary,           '')), 'C')
        ) STORED;

CREATE INDEX IF NOT EXISTS user_files_tsv_gin_idx
    ON user_files USING GIN (tsv)
    WHERE is_active = true;

CREATE OR REPLACE FUNCTION sync_content_type_description_to_file_comments()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.description IS DISTINCT FROM OLD.description THEN
        UPDATE user_files
        SET comment = NEW.description,
            updated_at = NOW()
        WHERE content_type_id = NEW.id
          AND is_active = true;
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_content_types_description_to_file_comments ON content_types;

CREATE TRIGGER trg_content_types_description_to_file_comments
AFTER UPDATE OF description ON content_types
FOR EACH ROW
EXECUTE FUNCTION sync_content_type_description_to_file_comments();

COMMENT ON FUNCTION sync_content_type_description_to_file_comments() IS
    'Mirrors content_types.description into user_files.comment for category-backed files only. '
    'Does not mirror embeddings; abstract search reads category distances from a pre-built CTE.';

